using UberSy.Application.Common.Interfaces;
using UberSy.Domain.Common.Results;
using UberSy.Domain.Restaurants;
using UberSy.Domain.Restaurants.AddOns;
using UberSy.Domain.Restaurants.Categories;
using UberSy.Domain.Restaurants.Items;
using UberSy.Domain.Restaurants.Printers;
using UberSy.Test.Common.Restaurants;
using UberSy.Test.Common.Security;

namespace UberSy.Api.IntegrationTests.Common;

public static class RestaurantTestData
{
    public static async Task<TbRestaurant> SeedRestaurantAsync(
        IApplicationDbContext context,
        Guid? ownerId = null,
        bool approved = false,
        bool open = false,
        string? nameAr = null,
        string? nameEn = null)
    {
        var result = RestaurantFactory.CreateRestaurant(
            ownerId: ownerId ?? TestUsers.Owner1.Id,
            nameAr: nameAr ?? "مطعم تجريبي",
            nameEn: nameEn ?? "Test Restaurant");

        var restaurant = Unwrap(result);

        if (approved || open) restaurant.Approve();
        if (open) restaurant.Open();

        context.TbRestaurants.Add(restaurant);
        await context.SaveChangesAsync(CancellationToken.None);
        return restaurant;
    }

    public static async Task<TbPrinter> SeedPrinterAsync(
        IApplicationDbContext context,
        Guid restaurantId,
        bool active = true)
    {
        // TbPrinter has no factory; the key is generated by EF on Add
        var printer = new TbPrinter
        {
            RestaurantId = restaurantId,
            Type = 1,
            Name = "Kitchen Printer",
            ConnectionInfo = "192.168.1.50",
            IsActive = active
        };

        context.TbPrinters.Add(printer);
        await context.SaveChangesAsync(CancellationToken.None);
        return printer;
    }

    public static async Task<TbCategory> SeedCategoryAsync(
        IApplicationDbContext context,
        Guid restaurantId,
        Guid? printerId = null,
        bool active = true,
        byte sortOrder = 1,
        string? nameAr = null,
        string? nameEn = null)
    {
        var category = Unwrap(CategoryFactory.CreateCategory(
            restaurantId: restaurantId,
            printerId: printerId,
            nameAr: nameAr,
            nameEn: nameEn,
            sortOrder: sortOrder));

        if (!active) category.Deactivate();

        context.TbCategories.Add(category);
        await context.SaveChangesAsync(CancellationToken.None);
        return category;
    }

    public static async Task<TbItem> SeedItemAsync(
        IApplicationDbContext context,
        Guid restaurantId,
        Guid categoryId,
        bool active = true,
        decimal price = 25m,
        byte sortOrder = 1)
    {
        var item = Unwrap(ItemFactory.CreateItem(
            restaurantId: restaurantId,
            categoryId: categoryId,
            price: price,
            sortOrder: sortOrder));

        if (!active) item.Deactivate();

        context.TbItems.Add(item);
        await context.SaveChangesAsync(CancellationToken.None);
        return item;
    }

    public static async Task<TbAddOn> SeedAddOnAsync(
        IApplicationDbContext context,
        Guid restaurantId,
        bool active = true,
        decimal price = 2.5m)
    {
        var addOn = Unwrap(AddOnFactory.CreateAddOn(restaurantId: restaurantId, price: price));

        if (!active) addOn.Deactivate();

        context.TbAddOns.Add(addOn);
        await context.SaveChangesAsync(CancellationToken.None);
        return addOn;
    }

    public static async Task AssignAddOnAsync(IApplicationDbContext context, TbItem item, TbAddOn addOn)
    {
        var result = item.AssignAddOn(addOn);
        if (result.IsError)
            throw new InvalidOperationException($"{result.TopError.Code}: {result.TopError.Description}");

        await context.SaveChangesAsync(CancellationToken.None);
    }

    private static T Unwrap<T>(Result<T> result)
        => result.IsError
            ? throw new InvalidOperationException($"Factory produced invalid data: {result.TopError.Code} - {result.TopError.Description}")
            : result.Value;
}
